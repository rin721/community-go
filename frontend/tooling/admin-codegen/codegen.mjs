async function exists(path) {
  try {
    await readFile(path);
    return true;
  } catch {
    return false;
  }
}

async function walk(directory) {
  if (!existsSync(directory)) return [];
  const files = [];
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(fullPath)));
    else files.push(fullPath);
  }
  return files;
}

function toPosix(path) {
  return path.split(sep).join('/');
}

async function loadTypeScriptModule(path) {
  return import(pathToFileURL(path).href);
}

function escapeIdentifier(name) {
  return name.replace(/[^A-Za-z0-9_]/g, '_');
}

/** routeId → generated bridge 文件名（无扩展）。 */
function bridgeFileName(routeId) {
  return escapeIdentifier(routeId);
}

/** routeId → Host 薄入口内的 bridge export 名。 */
function hostBridgeExportName(route) {
  return `AdminRouteBridge_${bridgeFileName(route.descriptor.routeId)}`;
}

