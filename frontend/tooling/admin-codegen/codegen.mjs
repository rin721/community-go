const forbiddenPageExports = [
  'generateStaticParams',
  'generateMetadata',
  'generateViewport',
  'revalidate',
  'dynamic',
  'runtime',
  'preferredRegion',
  'fetchCache',
  'maxDuration',
  'dynamicParams',
];

function forbiddenPageExportFound(content) {
  return forbiddenPageExports.filter((name) => {
    const pattern = new RegExp(
      `export\\s+(?:const|let|function)\\s+${name}\\b|export\\s*\\{\\s*${name}\\b`,
    );
    return pattern.test(content);
  });
}

/** 解析 Plugin Page 的具名组件导出；确定性：全文件必须恰好导出一个组件函数。 */
async function resolvePageComponent(pagePath) {
  const content = await readFile(pagePath, 'utf8');
  const exports = [];
  const namedFunction = /export\s+function\s+([A-Za-z_$][\w$]*)\s*\(/g;
  for (const match of content.matchAll(namedFunction)) exports.push(match[1]);
  // export default function Name 也视为组件
  const defaultFunction = /export\s+default\s+function\s+([A-Za-z_$][\w$]*)\s*\(/;
  const defaultMatch = defaultFunction.exec(content);
  if (defaultMatch) exports.push(defaultMatch[1]);
  if (exports.length !== 1) {
    throw new Error(
      `${pagePath}: Plugin Page 必须恰好导出一个具名组件函数（找到 ${exports.length} 个：${exports.join(', ') || '无'}）`,
    );
  }
  return exports[0];
}

async function scanRoutesTree(plugin) {
  const routesDir = join(plugin.dir, 'routes');
  if (!existsSync(routesDir)) return [];
  const files = await walk(routesDir);
  const pageByDir = new Map();
  const metaByDir = new Map();
  for (const file of files) {
    const local = toPosix(relative(routesDir, file));
    const isPage = /page\.tsx?$/.test(local);
    const isMeta = local.endsWith('route.meta.ts');
    if (!isPage && !isMeta) continue;
    const dir = local.includes('/') ? local.slice(0, local.lastIndexOf('/')) : '';
    if (isPage) pageByDir.set(dir, file);
    if (isMeta) metaByDir.set(dir, file);
  }

  for (const dir of metaByDir.keys()) {
    if (!pageByDir.has(dir)) {
      throw new Error(
        `plugins/${plugin.definition.pluginId}/routes/${dir || '.'}: route.meta.ts 缺少 1:1 的 page.tsx`,
      );
    }
  }
  for (const dir of pageByDir.keys()) {
    if (!metaByDir.has(dir)) {
      throw new Error(
        `plugins/${plugin.definition.pluginId}/routes/${dir || '.'}: page.tsx 缺少 1:1 的 route.meta.ts`,
      );
    }
  }

  const routes = [];
  for (const dir of [...pageByDir.keys()].sort()) {
    const pagePath = pageByDir.get(dir);
    const metaPath = metaByDir.get(dir);
    for (const segment of dir === '' ? [] : dir.split('/')) {
      if (
        segment.includes('...') ||
        segment.startsWith('(') ||
        segment.startsWith('@') ||
        /^\[\[.+]]$/.test(segment)
      ) {
        throw new Error(
          `plugins/${plugin.definition.pluginId}/routes/${dir || '.'}: 禁止 catch-all、parallel、route group（${segment}）`,
        );
      }
    }
    const pageContent = await readFile(pagePath, 'utf8');
    const forbidden = forbiddenPageExportFound(pageContent);
    if (forbidden.length > 0) {
      throw new Error(
        `plugins/${plugin.definition.pluginId}/routes/${dir || '.'}: 禁止 Next 专用导出 ${forbidden.join(', ')}`,
      );
    }
    const metaModule = await loadTypeScriptModule(metaPath);
    const routeMeta = metaModule?.routeMeta;
    if (!routeMeta || typeof routeMeta !== 'object') {
      throw new Error(
        `plugins/${plugin.definition.pluginId}/routes/${dir || '.'}: route.meta.ts 必须导出 routeMeta`,
      );
    }
    const componentExport = await resolvePageComponent(pagePath);
    const descriptor = buildDescriptor(plugin, dir, routeMeta);
    validateRouteMetaContract(plugin, dir, descriptor, routeMeta);
    routes.push({ dir, pagePath, metaPath, descriptor, componentExport });
  }
  return [...routes].sort((a, b) => a.descriptor.routeId.localeCompare(b.descriptor.routeId));
}

function buildDescriptor(plugin, relativeDir, routeMeta) {
  const pluginId = plugin.definition.pluginId;
  const segments = relativeDir === '' ? [] : relativeDir.split('/');
  const routeId = relativeDir === '' ? pluginId : `${pluginId}.${relativeDir.split('/').join('.')}`;
  const pattern =
    segments.length === 0
      ? plugin.definition.mount
      : `${plugin.definition.mount}/${segments.join('/')}`;
  const paramNames = segments
    .filter((segment) => /^\[[A-Za-z0-9_]+]$/.test(segment))
    .map((segment) => segment.slice(1, -1));

  return {
    routeId,
    pluginId,
    path: segments.join('/'),
    segments,
    pattern,
    paramNames,
    ...(routeMeta.titleKey ? { titleKey: routeMeta.titleKey } : {}),
    ...(routeMeta.canonicalParentOverride
      ? { canonicalParentOverride: routeMeta.canonicalParentOverride }
      : {}),
    ...(routeMeta.activeNavigationOverride
      ? { activeNavigationOverride: routeMeta.activeNavigationOverride }
      : {}),
    ...(routeMeta.permissions?.length ? { permissions: routeMeta.permissions } : {}),
  };
}

function validateRouteMetaContract(plugin, relativeDir, descriptor, routeMeta) {
  const errors = [];
  const pluginId = plugin.definition.pluginId;
  if (routeMeta.navigation) {
    errors.push('route.meta 不再支持 navigation（Sidebar 贡献迁移到 plugin.navigation.ts）');
  }
  if (routeMeta.canonicalParentOverride) {
    const override = routeMeta.canonicalParentOverride;
    if (typeof override.routeId !== 'string' || override.routeId.split('.')[0] !== pluginId) {
      errors.push('canonicalParentOverride.routeId 必须引用同 Plugin Route');
    }
    if (typeof override.rationale !== 'string' || !override.rationale.trim()) {
      errors.push('canonicalParentOverride 必须提供 rationale');
    }
  }
  if (routeMeta.activeNavigationOverride) {
    const override = routeMeta.activeNavigationOverride;
    if (
      typeof override.navigationId !== 'string' ||
      override.navigationId.split('.')[0] !== pluginId
    ) {
      errors.push('activeNavigationOverride.navigationId 必须为同 Plugin namespace');
    }
    if (typeof override.rationale !== 'string' || !override.rationale.trim()) {
      errors.push('activeNavigationOverride 必须提供 rationale');
    }
  }
  if (errors.length > 0) {
    throw new Error(
      `plugins/${pluginId}/routes/${relativeDir || '.'}: metadata 契约失败\n${errors.map((item) => `- ${item}`).join('\n')}`,
    );
  }
}

function validateCatalogConflicts(allRoutes, plugins) {
  const routeIds = new Set();
  const patterns = new Set();
  const mounts = new Set();
  const errors = [];
  for (const route of allRoutes) {
    if (routeIds.has(route.descriptor.routeId)) {
      errors.push(`重复 routeId: ${route.descriptor.routeId}`);
    }
    routeIds.add(route.descriptor.routeId);
    if (patterns.has(route.descriptor.pattern)) {
      errors.push(`重复 pattern: ${route.descriptor.pattern}`);
    }
    patterns.add(route.descriptor.pattern);
  }
  for (const plugin of plugins) {
    if (mounts.has(plugin.definition.mount)) {
      errors.push(`mount 冲突: ${plugin.definition.mount}`);
    }
    mounts.add(plugin.definition.mount);
  }
  if (errors.length > 0) {
    throw new Error(`Catalog 冲突:\n${errors.map((item) => `- ${item}`).join('\n')}`);
  }
}

/**
 * 加载 plugins 范围公共 Group Alias（navigation-groups.ts，单一 authority）。
 */
async function loadGroupAliases() {
  const module = await loadTypeScriptModule(navigationGroupsPath);
  const aliases = module?.adminNavigationGroupAliases;
  if (!Array.isArray(aliases)) {
    throw new Error('无法加载 Group Alias 公共契约（plugins/navigation-groups.ts）');
  }
  return aliases;
}

/**
 * Navigation Group Alias gate：每个 contribution parent 的 groupId 必须命中
 * plugins 范围 Group Alias（navigation-groups.ts）。未知 Alias deterministic fail，
 * 禁止 silent drop。
 */
async function validateGroupAliasReferences(plugins) {
  const aliases = await loadGroupAliases();
  const aliasIds = new Set(aliases.map((alias) => alias.groupId));
  const violations = [];
  for (const plugin of plugins) {
    const contribution = plugin.navigationContribution;
    if (!contribution) continue;
    for (const parent of contribution.parents ?? []) {
      if (!aliasIds.has(parent.groupId)) {
        violations.push(
          `[UNKNOWN_ADMIN_NAVIGATION_GROUP] ${plugin.definition.pluginId}: ${parent.navigationId} 引用不存在的 Group Alias: ${parent.groupId}`,
        );
      }
    }
  }
  if (violations.length > 0) {
    throw new Error(
      `Navigation Group Alias gate 失败:\n${violations.map((v) => `- ${v}`).join('\n')}`,
    );
  }
}

/**
 * Navigation icon vocabulary gate：contribution parent/child 的 iconId 必须命中
 * Admin Surface icon vocabulary（navigation-icon.ts，受控语义不动态化）。
 */
async function validateNavigationIconReferences(plugins) {
  const iconModule = await loadTypeScriptModule(surfaceIconVocabularyPath);
  const collect = iconModule?.collectUnknownNavigationIconDiagnostics;
  if (typeof collect !== 'function') {
    throw new Error('无法加载 Admin Surface icon vocabulary authority（navigation-icon.ts）');
  }
  const references = [];
  for (const plugin of plugins) {
    const contribution = plugin.navigationContribution;
    if (!contribution) continue;
    for (const parent of contribution.parents ?? []) {
      if (parent.iconId) {
        references.push({ iconId: parent.iconId, routeId: parent.navigationId });
      }
      for (const child of parent.children ?? []) {
        if (child.iconId) references.push({ iconId: child.iconId, routeId: child.navigationId });
      }
    }
  }
  const diagnostics = collect(references);
  if (diagnostics.length > 0) {
    throw new Error(
      `Navigation icon vocabulary gate 失败 (${diagnostics[0].code}):\n${diagnostics
        .map((diagnostic) => `- [${diagnostic.code}] ${diagnostic.message}`)
        .join('\n')}`,
    );
  }
}

/**
 * discovery + 全部 deterministic semantic validation。
 * generateAll 与 checkFreshness 共用同一校验链，保证两入口规则一致。
 */
async function collectSurface() {
  const plugins = await discoverSurface();
  const collected = [];
  for (const plugin of plugins) {
    collected.push({ plugin, routes: await scanRoutesTree(plugin) });
  }
  const allRoutes = collected.flatMap((item) => item.routes);
  validateCatalogConflicts(allRoutes, plugins);
  const aliases = await loadGroupAliases();
  await validateGroupAliasReferences(plugins);
  await validateNavigationIconReferences(plugins);
  const dynamic = allRoutes.filter((route) => route.descriptor.paramNames.length > 0);
  if (dynamic.length > 0) {
    throw new Error(
      `Host capability gate 失败 (UNSUPPORTED_DYNAMIC_PLUGIN_ROUTE): Static Export Host 不支持动态 Plugin Route\n${dynamic
        .map((route) => `- ${route.descriptor.routeId} (${route.descriptor.pattern})`)
        .join('\n')}`,
    );
  }
  return { plugins, allRoutes, aliases };
}

