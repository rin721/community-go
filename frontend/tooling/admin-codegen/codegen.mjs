/**
 * admin-codegen —— 确定性 Admin Surface Codegen 工具（Architecture Gate 执行点）。
 *
 * 职责边界：
 * - Discovery：扫描 surfaces/admin/plugins/ 下各 plugin 的 plugin.ts 与 routes 树
 *   （每个路由目录一对 page 文件与 route.meta 文件）。
 * - Contract Validation：静态校验 1:1 配对、禁止 Next exports、namespace、override、冲突。
 * - Framework Descriptors：只生成静态 descriptors / catalog / bridges / composition / i18n。
 * - Host Capability Analysis：Static Export Host 对 [param] 路由返回 UNSUPPORTED_DYNAMIC_PLUGIN_ROUTE，
 *   不生成 Next 入口并令 gate 失败（硬失败，不降级、不 generateStaticParams）。
 * - Host Route Generation：为静态 Route 生成 apps/admin-web/src/app/<mount>/... 薄入口。
 *
 * Registry（canonical hierarchy / navigation inheritance / breadcrumb / command / permission）
 * 由 @community-go/admin-framework registry 在运行时完成，Generator 不复制该逻辑。
 *
 * 本工具不执行 React 代码；route.meta.ts 通过 Node 24 type-stripping 静态加载。
 * 生成物全部带 `// @generated` 头；freshness check 逐文件重建比较（missing / drift / stale）。
 */

import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import prettier from 'prettier';

const frontendRoot = resolve(import.meta.dirname, '..', '..');
const surfaceRoot = join(frontendRoot, 'surfaces', 'admin');
const pluginsRoot = join(surfaceRoot, 'plugins');
const generatedRoot = join(surfaceRoot, 'generated');
const hostAppRoot = join(frontendRoot, 'apps', 'admin-web', 'src', 'app');
const surfacePackageName = '@community-go/admin-surface';

export const GENERATED_HEADER =
  '// @generated by tooling/admin-codegen —— 不要手改，运行 `pnpm codegen:admin` 重新生成。';

/* ------------------------------------------------------------------ */
/* Small helpers                                                       */
/* ------------------------------------------------------------------ */

async function exists(path) {
  try {
    await readFile(path);
    return true;
  } catch {
    return false;
  }
}

async function walk(directory) {
  if (!existsSync(directory)) return [];
  const files = [];
  const entries = await readdir(directory, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const fullPath = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(fullPath)));
    else files.push(fullPath);
  }
  return files;
}

function toPosix(path) {
  return path.split(sep).join('/');
}

async function loadTypeScriptModule(path) {
  return import(pathToFileURL(path).href);
}

function escapeIdentifier(name) {
  return name.replace(/[^A-Za-z0-9_]/g, '_');
}

/** routeId → generated bridge 文件名（无扩展）。 */
function bridgeFileName(routeId) {
  return escapeIdentifier(routeId);
}

